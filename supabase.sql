drop policy if exists "piloto_clientes_select" on public.clientes;
drop policy if exists "piloto_clientes_insert" on public.clientes;
drop policy if exists "piloto_orcamentos_select" on public.orcamentos;
drop policy if exists "piloto_orcamentos_insert" on public.orcamentos;
drop policy if exists "piloto_orcamentos_update" on public.orcamentos;
drop policy if exists "piloto_itens_select" on public.itens_orcamento;
drop policy if exists "piloto_itens_insert" on public.itens_orcamento;

create policy "piloto_clientes_select" on public.clientes for select to anon using (true);
create policy "piloto_clientes_insert" on public.clientes for insert to anon with check (true);
create policy "piloto_orcamentos_select" on public.orcamentos for select to anon using (true);
create policy "piloto_orcamentos_insert" on public.orcamentos for insert to anon with check (true);
create policy "piloto_orcamentos_update" on public.orcamentos for update to anon using (true) with check (true);
create policy "piloto_itens_select" on public.itens_orcamento for select to anon using (true);
create policy "piloto_itens_insert" on public.itens_orcamento for insert to anon with check (true);

grant select, insert on public.clientes to anon;
grant select, insert, update on public.orcamentos to anon;
grant select, insert on public.itens_orcamento to anon;
grant usage, select on all sequences in schema public to anon;

